export function listMotionBlocks(): MotionBlock[] {
    return motionBlocks;
}

export function listBlueprints(): CinematicBlueprint[] {
    return cinematicBlueprints;
}

export function getMotionBlock(id: string): MotionBlock | undefined {
    return motionBlocks.find((b) => b.id === id);
}

export function getBlueprint(id: string): CinematicBlueprint | undefined {
    return cinematicBlueprints.find((b) => b.id === id);
}

export function getBlocksForStyle(style: string): MotionBlock[] {
    return motionBlocks.filter(
        (b) => b.styleAffinity.includes('any') || b.styleAffinity.includes(style as StyleAffinity)
    );
}
