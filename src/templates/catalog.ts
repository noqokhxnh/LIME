function recipe(
    id: string,
    name: string,
    description: string,
    category: MotionBlock['category'],
    beatRole: MotionBlock['beatRole'],
    tags: string[],
    promptSnippet: string,
    styleAffinity: StyleAffinity[] = ['any']
): MotionBlock {
    return {
        id,
        name,
        description,
        category,
        tags,
        styleAffinity,
        beatRole,
        runtime: false,
        promptSnippet,
    };
}

